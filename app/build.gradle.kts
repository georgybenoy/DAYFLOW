    signingConfigs {
        create("release") {
            val keystorePropertiesFile = rootProject.file("keystore.properties")
            if (keystorePropertiesFile.exists()) {
                val properties = Properties()
                properties.load(keystorePropertiesFile.inputStream())
                storeFile = file(properties.getProperty("storeFile") ?: "keystore.jks")
                storePassword = properties.getProperty("storePassword")
                keyAlias = properties.getProperty("keyAlias")
                keyPassword = properties.getProperty("keyPassword")
            } else if (System.getenv("DAYFLOW_KEYSTORE_PATH") != null) {
                storeFile = file(System.getenv("DAYFLOW_KEYSTORE_PATH")!!)
                storePassword = System.getenv("DAYFLOW_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("DAYFLOW_KEY_ALIAS")
                keyPassword = System.getenv("DAYFLOW_KEY_PASSWORD")
            } else {
                // Fallback to debug signing for verification builds when production keystore is absent
                val debugSigning = getByName("debug")
                storeFile = debugSigning.storeFile
                storePassword = debugSigning.storePassword
                keyAlias = debugSigning.keyAlias
                keyPassword = debugSigning.keyPassword
            }
        }
    }

